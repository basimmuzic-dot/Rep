def run(k=5, verbose=False):
    db = sqlite3.connect(kb.db_path())
    hit = 0
    for q, law, phrase in CASES:
        res = [r for r in kb.search(q, k=k) if "law" in r]
        want = kb.norm(phrase)
        ok = False
        for r in res:
            if law in r["law"]:
                full = db.execute("SELECT text FROM articles WHERE id=?", (r["id"],)).fetchone()[0]
                if want in kb.norm(full):
                    ok = True
                    break
        hit += ok
        if verbose or not ok:
            print(("OK  " if ok else "MISS"), q, "|", law, "|", [r["law"][:18] + "/" + r["article"][:16] for r in res[:3]] if not ok else "")
    print(f"{hit}/{len(CASES)} in top {k}")
    return hit


if __name__ == "__main__":
    k = int(sys.argv[sys.argv.index("--k") + 1]) if "--k" in sys.argv else 5
    run(k, "-v" in sys.argv)
