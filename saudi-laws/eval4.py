def run(k=5, verbose=False):
    import sqlite3
    db = sqlite3.connect(kb.db_path())
    hit = 0
    for q, law, phrase in eval3.CASES:
        res = [r for r in kb.search(q, k=k, queries=PHRASINGS[q]) if "law" in r]
        want, ok = kb.norm(phrase), False
        for r in res:
            if law in r["law"] and want in kb.norm(db.execute("SELECT text FROM articles WHERE id=?", (r["id"],)).fetchone()[0]):
                ok = True
                break
        hit += ok
        if verbose or not ok:
            print(("OK  " if ok else "MISS"), q, "|", law, "|" if ok else "|", [] if ok else [r["law"][:18] + "/" + r["article"][:16] for r in res[:3]])
    print(f"{hit}/{len(eval3.CASES)} in top {k}  (4 phrasings per question, as in production)")


if __name__ == "__main__":
    run(int(sys.argv[sys.argv.index("--k") + 1]) if "--k" in sys.argv else 5, "-v" in sys.argv)
