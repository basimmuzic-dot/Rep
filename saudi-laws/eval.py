"""Ranking check: each topic query must surface the expected law in the top results.  python3 eval.py"""
import sys
import kb

CASES = [  # (query, substring of the law title that should appear in the top k)
    ("العقوبة على الرشوة", "الرشوة"), ("عقوبة غسل الأموال", "غسل"), ("الإجازة السنوية للعامل", "نظام العمل"),
    ("ينتهي عقد العمل", "نظام العمل"), ("مكافأة نهاية الخدمة", "نظام العمل"), ("حضانة الطفل بعد الطلاق", "الأحوال الشخصية"),
    ("تأسيس شركة ذات مسؤولية محدودة", "الشركات"), ("الشيك بدون رصيد", "الأوراق التجارية"),
    ("إيجار العقار وإخلاء المستأجر", "الإيجار"), ("التقادم المسقط للدعوى", "المعاملات المدنية"),
    ("حجز أموال المدين", "التنفيذ"), ("شروط الحبس الاحتياطي", "الإجراءات الجزائية"),
    ("مكافحة التستر التجاري", "التستر"), ("حماية البيانات الشخصية", "البيانات الشخصية"),
    ("عقوبة التزوير", "التزوير"), ("الإفلاس والتصفية", "الإفلاس"), ("حقوق المؤلف", "حماية حقوق المؤلف"),
    ("حماية المستهلك", "المستهلك"), ("ضريبة القيمة المضافة", "القيمة المضافة"), ("مكافحة الجرائم المعلوماتية", "المعلوماتية"),
]

def run(k=5):
    hit = 0
    for q, want in CASES:
        laws = [r["law"] for r in kb.search(q, k=k) if "law" in r]
        ok = any(want in l for l in laws)
        hit += ok
        if "-v" in sys.argv or not ok:
            print(("OK  " if ok else "MISS"), q, "|", want, "|", [l[:25] for l in laws[:3]] if not ok else "")
    print(f"{hit}/{len(CASES)} in top {k}")
    return hit

if __name__ == "__main__":
    run()
